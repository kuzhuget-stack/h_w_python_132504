import math
a = input("Введите длину первой стороны: ")
b = input("Введите длину второй стороны: ")
c = input("Введите угол между ними в градусах: ")
a, b, c = float(a), float(b), float(c) # перевод строки в число
an_radians = math.radians(c) # переводим градусы в радианы, чтобы питон смог высчитать косинус
cosss = a**2 + b**2 - 2*a*b*math.cos(an_radians) # считаем по теореме косинусов
s = math.sqrt(cosss) # извлечем корень
print("Длина третьей стороны: ", s)